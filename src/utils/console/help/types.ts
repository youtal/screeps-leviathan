/**
 * 文件摘要
 *
 * 模块角色：utils/console/help 的描述数据协议，规定调用方如何向渲染器提供帮助内容。
 *
 * 主要功能：声明模块名称、介绍与 API 列表，以及函数标题、参数说明、入口名和调用形式。
 *
 * 实现过程：ModuleDescribe 包含 FunctionDescribe 数组，函数描述以可选字段表示省略说明或参数，
 * commandType 标记生成示例时是否省略括号。
 *
 * 技术要点：参数数组顺序同时决定展示顺序和调用示例中的参数顺序；数据中没有实际函数回调。
 * 这里只定义类型，不生成 HTML 或读取 Game，渲染逻辑由 createHelp 完成。
 */
/**
 * 单个模块的帮助元数据。
 */
export interface ModuleDescribe {
  /**
   * 模块名
   *
   * 显示为模块标题（黄色），也是控制台里识别帮助归属的主要标识。
   */
  name: string;
  /**
   * 模块介绍
   *
   * 显示在标题右侧（绿色），用于一句话说明模块职责；不做长度限制，
   * 但过长会挤压同一行的 API 列表。
   */
  describe: string;
  /**
   * 该模块的 api 列表
   *
   * 每项渲染为一个可折叠的 API 卡片；空数组表示该模块只展示标题与介绍。
   */
  api: FunctionDescribe[];
}

/**
 * 单个函数或控制台命令的帮助元数据。
 */
export interface FunctionDescribe {
  /**
   * 函数的名字
   *
   * 说明性短标题，与 functionName 一起构成折叠卡片的标题栏。
   */
  title: string;
  /**
   * 函数如何使用
   *
   * 可选的用法说明，存在时渲染为卡片内的第一行；省略则直接展示参数与调用示例。
   */
  describe?: string;
  /**
   * 参数列表
   * 置空则没有参数
   *
   * 每项包含参数名与介绍，渲染为带缩进的参数行；同时参数名会按顺序拼进调用示例的
   * 括号中，因此这里的顺序应当与真实形参一致。
   */
  params?: {
    /**
     * 参数名
     */
    name: string;
    /**
     * 参数介绍
     */
    desc: string;
  }[];
  /**
   * 函数的方法名
   *
   * 真实可从控制台调用的入口名，渲染为调用示例并参与折叠控件的 id 生成。
   */
  functionName: string;
  /**
   * 是否可以直接执行：不需要使用 () 就可以执行的命令
   *
   * 为 true 时调用示例省略括号，用于属性式/命令式入口；缺省按普通函数渲染。
   */
  commandType?: boolean;
}
