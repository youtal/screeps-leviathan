/**
 * 文件摘要：声明控制台帮助渲染器接收的模块、函数和参数描述结构。
 *
 * 模块位置：src/utils/console/help 的类型契约文件，被 createHelp.ts 引用；
 * 本文件不含运行时值，编译后整体擦除，也不会把任何数据带进产物。
 *
 * 主要输入 / 输出：这些接口是 createHelp 的入参形状——调用方用纯数据描述模块与 API，
 * 渲染器据此产出 HTML。所有字段均为可序列化描述数据，不持有游戏对象；可选字段用于
 * 省略没有说明、参数或特殊调用形式的部分，因此帮助内容可以放在任意模块的静态常量里。
 */
/**
 * 单个模块的帮助元数据。
 */
export interface ModuleDescribe {
    /**
     * 模块名
     *
     * 显示为模块标题（黄色），也是控制台里识别帮助归属的主要标识。
     */
    name: string
    /**
     * 模块介绍
     *
     * 显示在标题右侧（绿色），用于一句话说明模块职责；不做长度限制，
     * 但过长会挤压同一行的 API 列表。
     */
    describe: string
    /**
     * 该模块的 api 列表
     *
     * 每项渲染为一个可折叠的 API 卡片；空数组表示该模块只展示标题与介绍。
     */
    api: FunctionDescribe[]
}

/**
 * 单个函数或控制台命令的帮助元数据。
 */
export interface FunctionDescribe {
    /**
     * 函数的名字
     *
     * 说明性短标题，与 functionName 一起构成折叠卡片的标题栏。
     */
    title: string
    /**
     * 函数如何使用
     *
     * 可选的用法说明，存在时渲染为卡片内的第一行；省略则直接展示参数与调用示例。
     */
    describe?: string
    /**
     * 参数列表
     * 置空则没有参数
     *
     * 每项包含参数名与介绍，渲染为带缩进的参数行；同时参数名会按顺序拼进调用示例的
     * 括号中，因此这里的顺序应当与真实形参一致。
     */
    params?: {
        /**
         * 参数名
         */
        name: string
        /**
         * 参数介绍
         */
        desc: string
    }[]
    /**
     * 函数的方法名
     *
     * 真实可从控制台调用的入口名，渲染为调用示例并参与折叠控件的 id 生成。
     */
    functionName: string
    /**
     * 是否可以直接执行：不需要使用 () 就可以执行的命令
     *
     * 为 true 时调用示例省略括号，用于属性式/命令式入口；缺省按普通函数渲染。
     */
    commandType?: boolean
}
